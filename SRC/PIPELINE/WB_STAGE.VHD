LIBRARY IEEE;
USE IEEE.std_logic_1164.ALL;
USE IEEE.numeric_std.ALL;

ENTITY WB_STAGE IS
    PORT(
        CLOCK : IN STD_LOGIC;
        RESET : IN STD_LOGIC;
        INSTRUCTION : IN STD_LOGIC_VECTOR(35 DOWNTO 0)
        DATA_OUT : OUT STD_LOGIC_VECTOR(INST_SIZE-1 downto 0);
        REGDST : OUT STD_LOGIC_VECTOR(3 downto 0);
    );
END WB_STAGE;

ARCHITECTURE COMPORTAMENTO OF WB_STAGE IS
    SIGNAL MUX_DATA : STD_LOGIC;
    SIGNAL MEMORY_RESULT : STD_LOGIC_VECTOR(INST_SIZE-1 downto 0);
    SIGNAL ULA_RESULT : STD_LOGIC_VECTOR(INST_SIZE-1 downto 0);
    SIGNAL RESULT : STD_LOGIC_VECTOR(INST_SIZE-1 downto 0);

    --ATRIBUIR SIGNALS PARA INTRUCAO
BEGIN
    PROCESS(CLOCK, RESET)
    BEGIN
        RESULT <= MEMORY_RESULT WHEN MUX_DATA IS '0' ELSE
        RESULT <= ULA_RESULT

        --ATRIBUIR REGDST PARA ISNTRUCAO
    END PROCESS;
END COMPORTAMENTO;