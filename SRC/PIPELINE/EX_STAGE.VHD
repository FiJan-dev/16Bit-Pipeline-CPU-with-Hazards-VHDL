LIBRARY IEEE;
USE IEEE.std_logic_1164.ALL;
USE IEEE.numeric_std.ALL;
USE WORK.CPU_package.ALL;

ENTITY EX_STAGE is
    PORT (
        CLOCK : IN STD_LOGIC;
        RESET : IN STD_LOGIC;
        DATA_IN : IN DATA_REG_ID_EX;
        DATA_OUT: OUT DATA_REG_EX_MEM
    );
END EX_STAGE;

architecture COMPORTAMENTO OF EX_STAGE is
    SIGNAL RS_DATA : DATA_T;
    SIGNAL RT_DATA : DATA_T;
    SIGNAL IMM_EXT : DATA_T;
    SIGNAL A_DATA : STD_LOGIC_VECTOR(DATA_SIZE-1 DOWNTO 0);
    SIGNAL B_DATA : STD_LOGIC_VECTOR(DATA_SIZE-1 DOWNTO 0);
    SIGNAL RT : STD_LOGIC_VECTOR(3 DOWNTO 0);
    SIGNAL RD : STD_LOGIC_VECTOR(3 DOWNTO 0);
    SIGNAL FUNC, REG_DST, ALU_SRC : STD_LOGIC;

    SIGNAL MUX_ULASRCA : STD_LOGIC_VECTOR(DATA_SIZE-1 DOWNTO 0);
    SIGNAL MUX_ULASRCB : STD_LOGIC_VECTOR(DATA_SIZE-1 DOWNTO 0);
    SIGNAL RESULT : STD_LOGIC_VECTOR(DATA_SIZE-1 DOWNTO 0);
    SIGNAL CARRY : STD_LOGIC;
    SIGNAL OVERFLOW : STD_LOGIC;
    SIGNAL MUX_WBREGISTER : STD_LOGIC;
    SIGNAL WB_REGISTER : STD_LOGIC_VECTOR(3 DOWNTO 0);
    --SINAL DE HAZARD
    --RECEBE DOIS SINAIS DO FOWARDING TAMBEM
    --ATRIBUIR SINAIS AOS VALORES DE DATA_OUT
BEGIN
    -- DATA_OUT <= FUNC & REG_DST & ALU_SRC & MEMREAD & MEMWRITE & MEM2REG & REGWRITE & RS_DATA & RT_DATA & IMM_X4 & RS & RT & RD;
    FUNC <= DATA_IN(66);
    REG_DST <= DATA_IN(65);
    ALU_SRC <= DATA_IN(64);
    RS_DATA <= DATA_IN(59 DOWNTO 44);
    RT_DATA <= DATA_IN(43 DOWNTO 28);
    IMM_EXT <= DATA_IN(27 DOWNTO 12);
    RS <= DATA_IN(11 DOWNTO 8);
    RT <= DATA_IN(7 DOWNTO 4);
    RD <= DATA_IN(3 DOWNTO 0);


--TODO://DESCONCATENAR DATA_IN
    ULA_ADDER: ULA PORT MAP( --CIN, B, A, ULA_OUT, COUT, OVERFLOW);

    PROCESS(CLOCK, RESET)
    BEGIN
        --FAZER LOGICA DOS TRES MUXES ALU_SRC_B, FOWARD_A FOWARD_B
        A_DATA <= RS_DATA WHEN MUX_ULASRCA IS "00"ELSE  
        A_DATA <=         WHEN MUX_ULASRCA IS "01"ELSE
        A_DATA <=         WHEN MUX_ULASRCA IS "11"

        B_DATA <= RT_DATA WHEN MUX_ULASRCA IS "00"ELSE  
        B_DATA <= IMM_EXT WHEN MUX_ULASRCA IS "01"ELSE
        B_DATA <=         WHEN MUX_ULASRCA IS "11"

        WB_REGISTER <= RT WHEN MUX_WBREGISTER IS '0' ELSE
        WB_REGISTER <= RD

    END PROCESS;

    DATA_OUT <= DATA_IN(63 DOWNTO 60) & RESULT & B_DATA & WB_REGISTER;
END COMPORTAMENTO;

        

