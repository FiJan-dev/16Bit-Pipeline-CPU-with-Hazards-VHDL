LIBRARY IEEE;
USE IEEE.std_logic_1164.ALL;
USE IEEE.numeric_std.ALL;

USE work.CPU_package.all;

ENTITY CPU is
    PORT (
        CLOCK: IN STD_LOGIC;
        RESET: IN STD_LOGIC
        --INSTANCIAR CONTEUDO LEDS
    );
END CPU;

ARCHITECTURE COMPOSICAO OF CPU IS
    SIGNAL PC :STD_LOGIC_VECTOR(ADDR_SIZE-1 DOWNTO 0) := (others => '0');
begin
    IF_ST: IF_STAGE PORT MAP(CLOCK, RESET, PC_BRANCH, MUX_PC_SRC, DATA_IF_ID);
    IF_ID: IFID PORT MAP(CLOCK, RESET, DATA_IF_ID, DATA_ID);
    ID_ST: ID_STAGE PORT MAP(CLOCK, RESET, DATA_WB_ID, REG_DST, REGWRITE, DATA_ID, DATA_ID_EX);
    ID_EX: IDEX PORT MAP(CLOCK, RESET, MUX_FLUSH_ID, DATA_ID_EX, DATA_EX);
    EX: EX_STAGE PORT MAP(CLOCK, RESET, FOWARDING_DATA_MEM, DATA_EX, DATA_EX_MEM);
    EX_MEM: EXMEM PORT MAP(CLOCK, RESET, MUX_FLUSH_EX, DATA_EX_MEM, DATA_MEM);
    MEM_ST: MEM_STAGE PORT MAP(CLOCK, RESET, DATA_MEM, DATA_MEM_WB, FOWARDING_DATA_MEM);
    MEM_WB: MEMWB PORT MAP(CLOCK, RESET, DATA_MEM_WB, DATA_WB);
    WB_ST: WB_STAGE PORT MAP(CLOCK, RESET, DATA_WB, REGWRITE, DATA_WB_ID);
END COMPOSICAO;