LIBRARY IEEE;
USE IEEE.std_logic_1164.ALL;
USE IEEE.numeric_std.ALL;
USE WORK.CPU_package.ALL;

ENTITY ID_STAGE is
    GENERIC (
        ADDR_SIZE : INTEGER := 8
    );
    PORT (
        CLOCK : IN STD_LOGIC;
        RESET : IN STD_LOGIC;
        DATA_WB: IN DATA_T;
        REG_DST_ADDRESS : IN REG_ADDR_T;-- DATA_ID, DATA_ID_EX
        REGWRITE_WB : IN STD_LOGIC;
        DATA_IN: IN DATA_REG_IF_ID;
        DATA_OUT: OUT DATA_REG_ID_EX;
        PC_SRC : OUT STD_LOGIC_VECTOR(1 DOWNTO 0);
        JUMP_ADDR : OUT STD_LOGIC_VECTOR(12 DOWNTO 0);
        BRANCH_ADDRESS : OUT DATA_T
    );
END ID_STAGE;

ARCHITECTURE COMPORTAMENTO OF ID_STAGE is
    SIGNAL RS : REG_ADDR_T;
    SIGNAL RT : REG_ADDR_T;
    SIGNAL RD : REG_ADDR_T;
    SIGNAL RS_DATA, RT_DATA : DATA_T;
    SIGNAL IMM5 : STD_LOGIC_VECTOR(4 DOWNTO 0);
    SIGNAL IMM_EXT : DATA_T;
    SIGNAL IMM_X4 : DATA_T;
    SIGNAL PC : DATA_T;
    SIGNAL FUNC : STD_LOGIC;
    SIGNAL COMPARE : STD_LOGIC;
    SIGNAL OPCODE : STD_LOGIC_VECTOR(2 DOWNTO 0);
    SIGNAL ALU_SRC, REG_DST, MEMWRITE, MEMREAD, MEM2REG, REGWRITE: STD_LOGIC;
    SIGNAL CARRY, OVERFLOW : STD_LOGIC; --REMOVER DA ULA DPS SE NAO FOR USAR
begin 
    PC <= DATA_IN(31 DOWNTO 16);
    OPCODE <= DATA_IN(15 DOWNTO 13);
    RS <= DATA_IN(12 DOWNTO 9);
    RT <= DATA_IN(8 DOWNTO 5);
    RD <= DATA_IN(4 DOWNTO 1);
    FUNC <= DATA_IN(0);
    IMM5 <= DATA_IN(4 DOWNTO 0);
    JUMP_ADDR <= DATA_IN(12 DOWNTO 0);

    COMPARATOR_COMPONENT: COMPARATOR PORT MAP(RS_DATA, RT_DATA, COMPARE);
    REGBANK_INST: REGBANK PORT MAP(CLOCK, RESET, REGWRITE_WB, RS, RT, REG_DST_ADDRESS, DATA_WB, RS_DATA, RT_DATA);
    BRANCH_ADDER: ULA PORT MAP('0', IMM_X4, PC, BRANCH_ADDRESS, CARRY, OVERFLOW);
    SIGN_EXT_INST: SIGN_EXT PORT MAP(IMM5, IMM_EXT);
    SLL2: SHIFT_LEFT_2 PORT MAP(IMM_EXT, IMM_X4);
    CU: CONTROL_UNITY PORT MAP(CLOCK, RESET, OPCODE, COMPARE, FUNC, PC_SRC, ALU_SRC, REG_DST, MEMWRITE, MEMREAD, MEM2REG, REGWRITE);
    
    DATA_OUT <= FUNC & REG_DST & ALU_SRC & MEMREAD & MEMWRITE & MEM2REG & REGWRITE & RS_DATA & RT_DATA & IMM_EXT & RS & RT & RD;
END COMPORTAMENTO;