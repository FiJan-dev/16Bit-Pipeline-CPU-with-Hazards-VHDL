LIBRARY IEEE;
USE IEEE.std_logic_1164.ALL;
USE IEEE.numeric_std.ALL;
USE std.textio.ALL;
USE IEEE.std_logic_textio.ALL;

USE work.CPU_package.all;

ENTITY IF_STAGE is
    PORT (
        CLOCK : IN STD_LOGIC;
        RESET : IN STD_LOGIC;
		  PC_IN : IN DATA_T;
        PC_BRANCH : IN DATA_T;
        PC_JUMP : IN DATA_T;
        MUX_PC_SRC: IN STD_LOGIC_VECTOR(1 DOWNTO 0);
        DATA_IF_ID : OUT DATA_REG_IF_ID;
		  NEXT_PC_OUT: OUT DATA_T
    );
END IF_STAGE;

architecture COMPORTAMENTO OF IF_STAGE is
    SIGNAL NEXT_PC_INT : DATA_T := (OTHERS => '0');
    SIGNAL PC4         : DATA_T := (OTHERS => '0');
    SIGNAL DATA_STREAM : INST_T;
	 SIGNAL CARRY, OVERFLOW : STD_LOGIC;
BEGIN
    MEM_INST: MEMORY_INST PORT MAP(PC_IN, DATA_STREAM);
	 
	 PC_ADDER: ULA PORT MAP('0', PC_INCREMENT, PC_IN, PC4, CARRY, OVERFLOW);

    PROCESS(CLOCK, RESET, MUX_PC_SRC)
    begin
			IF RESET = '1' THEN
				NEXT_PC_INT <= (OTHERS => '0');
			ELSIF RISING_EDGE(CLOCK) THEN
				case MUX_PC_SRC is
					WHEN "00" => NEXT_PC_INT <= PC4; 
					WHEN "01" => NEXT_PC_INT <= PC_BRANCH;          
					WHEN "10" => NEXT_PC_INT <= PC_JUMP; 
					WHEN OTHERS =>	NEXT_PC_INT <= PC4;
				END CASE;
			END IF;
    END PROCESS;

    -- 16 - 16
    -- PC+4 - INST
    DATA_IF_ID(31 DOWNTO 16) <= PC4;
    DATA_IF_ID(15 DOWNTO 0) <= DATA_STREAM;
	 NEXT_PC_OUT <= NEXT_PC_INT;
END COMPORTAMENTO;
