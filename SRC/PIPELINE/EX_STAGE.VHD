LIBRARY IEEE;
USE IEEE.std_logic_1164.ALL;
USE IEEE.numeric_std.ALL;
USE WORK.CPU_package.ALL;

ENTITY EX_STAGE is
    PORT (
        CLOCK : IN STD_LOGIC;
        RESET : IN STD_LOGIC;
        REG_DST_WB, REG_DST_MEM : IN STD_LOGIC_VECTOR(3 DOWNTO 0);
        REG_WRITE_WB, REG_WRITE_MEM  : IN STD_LOGIC;
		  DATA_WB, DATA_MEM: IN DATA_T;
        DATA_IN : IN DATA_REG_ID_EX;
        DATA_OUT: OUT DATA_REG_EX_MEM
    );
END EX_STAGE;

architecture COMPORTAMENTO OF EX_STAGE is
    SIGNAL RS_DATA : DATA_T;
    SIGNAL RT_DATA : DATA_T;
    SIGNAL IMM_EXT : DATA_T;
    SIGNAL A_DATA : DATA_T;
    SIGNAL B_DATA : DATA_T;
	 SIGNAL B_INTERMED : DATA_T;
	 SIGNAL RS : STD_LOGIC_VECTOR(3 DOWNTO 0);
    SIGNAL RT : STD_LOGIC_VECTOR(3 DOWNTO 0);
    SIGNAL RD : STD_LOGIC_VECTOR(3 DOWNTO 0);
    SIGNAL FUNC, REG_DST, ALU_SRC : STD_LOGIC;

    SIGNAL MUX_SRCB : STD_LOGIC;
    SIGNAL RESULT : STD_LOGIC_VECTOR(DATA_SIZE-1 DOWNTO 0);
    SIGNAL CARRY : STD_LOGIC;
    SIGNAL OVERFLOW : STD_LOGIC;
    SIGNAL MUX_FORWARDINGB : STD_LOGIC;
    SIGNAL WB_REGISTER : STD_LOGIC_VECTOR(3 DOWNTO 0);
	 SIGNAL FOWARD_A, FOWARD_B : STD_LOGIC_VECTOR(1 DOWNTO 0);
    --SINAL DE HAZARD
    --RECEBE DOIS SINAIS DO FOWARDING TAMBEM
    --ATRIBUIR SINAIS AOS VALORES DE DATA_OUT
BEGIN
    FUNC <= DATA_IN(66);
    REG_DST <= DATA_IN(65);
    ALU_SRC <= DATA_IN(64);

    RS_DATA <= DATA_IN(59 DOWNTO 44);
    RT_DATA <= DATA_IN(43 DOWNTO 28);
    IMM_EXT <= DATA_IN(27 DOWNTO 12);
    RS <= DATA_IN(11 DOWNTO 8);
    RT <= DATA_IN(7 DOWNTO 4);
    RD <= DATA_IN(3 DOWNTO 0);
	 
    FU: FOWARDING_UNITY PORT MAP(CLOCK, RESET, RS, RT, REG_WRITE_MEM, REG_DST_MEM, REG_WRITE_WB, REG_DST_WB, FOWARD_A, FOWARD_B);
	 
    ULA_ADDER: ULA PORT MAP( FUNC, B_DATA, A_DATA, RESULT, CARRY, OVERFLOW);

    PROCESS(FOWARD_A, FOWARD_B, MUX_SRCB, REG_DST)
    BEGIN
      CASE FOWARD_A IS
			WHEN "00" =>
				A_DATA <= RS_DATA;
			WHEN "01" => 
				A_DATA <= DATA_WB;
			WHEN "10" =>
				A_DATA <= DATA_MEM;
			WHEN OTHERS =>
				A_DATA <= RS_DATA;
			END CASE;
			
		CASE MUX_SRCB IS
			WHEN '0' =>
				B_INTERMED <= RT_DATA;
			WHEN '1' =>
				B_INTERMED <= IMM_EXT;
			WHEN OTHERS =>
				B_INTERMED <= RT_DATA;
		END CASE;
		
		CASE FOWARD_B IS
			WHEN "00" =>
				B_DATA <= B_INTERMED;
			WHEN "01" =>
				B_DATA <= DATA_MEM;
			WHEN "10" =>
				B_DATA <= DATA_WB;
			WHEN OTHERS =>
				B_DATA <= B_INTERMED;
		END CASE;
		
		CASE REG_DST IS
			WHEN '0' =>
				WB_REGISTER <= RT;
			WHEN '1' =>
				WB_REGISTER <= RD;
			WHEN OTHERS =>
				WB_REGISTER <= RT;
		END CASE;
    END PROCESS;

    DATA_OUT <= DATA_IN(63 DOWNTO 60) & RESULT & B_DATA & WB_REGISTER;
END COMPORTAMENTO;

        

