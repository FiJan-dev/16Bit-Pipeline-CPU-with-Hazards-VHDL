LIBRARY IEEE;
USE IEEE.std_logic_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.CPU_package.ALL;

ENTITY SHIFT_LEFT_2 IS
    PORT(
        IMMEDIATE_EXT : IN DATA_T;
        IMMEDIATE_SHIFTED : OUT DATA_T
    );
END SHIFT_LEFT_2;

ARCHITECTURE LOGICA OF SHIFT_LEFT_2 is
begin
    IMMEDIATE_SHIFTED <= std_logic_vector(shift_left(unsigned(IMMEDIATE_EXT), 2));
END LOGICA;
